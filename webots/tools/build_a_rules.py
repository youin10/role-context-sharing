"""Generates the helper arm's rule files in config/a-helper from config/a-helper/source."""
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
from wcs.core import api  # noqa: E402
from arms.a.expand import targets, write_plans  # noqa: E402

H = os.path.join(ROOT, "config", "a-helper")
HEADER = "# Generated by tools/build_a_rules.py\n"


def load(name):
    with open(os.path.join(H, "source", name)) as f:
        return yaml.safe_load(f)


def main():
    signature, types = api.signature(), api.catalogue()[1]
    build, assign, revisions = load("build.yml"), load("assignments.yml"), load("revisions.yml")
    for rev, roles in revisions.items():
        write_plans({"roles": roles}, os.path.join(H, "plans", rev), signature, types, HEADER)
    for name, d in build["initials"].items():
        with open(os.path.join(H, name + ".yml"), "w") as f:
            f.write(HEADER)
            yaml.safe_dump({"plans": "plans/" + d["plans"], "agents": assign[d["assign"]]}, f, sort_keys=False)
    os.makedirs(os.path.join(H, "changes"), exist_ok=True)
    for name, c in build["changes"].items():
        (fa, fp), (ta, tp) = c["from"], c["to"]
        t = targets(assign[fa], assign[ta], os.path.join(H, "plans", fp), os.path.join(H, "plans", tp))
        with open(os.path.join(H, "changes", name + ".yml"), "w") as f:
            f.write(HEADER)
            yaml.safe_dump({"plans": "plans/" + tp, "targets": t}, f, sort_keys=False)


if __name__ == "__main__":
    main()
