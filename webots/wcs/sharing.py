"""Builds one sharing arm from the frozen core's run classes.

D derives its configuration from the .org model and binding. A uses hand-authored rule files.
H uses rule files generated by the core's helper; its runtime is the same as A's.
"""
import os

import yaml

from wcs.core import api, core_run, variants
from arms.a.expand import expand_role
from arms.a.typed import check_plans
from arms.d.generator import GenerationError
from arms.d.spec import OrgError

CONFIG = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "config"))
ARM_DIRS = {"A": os.path.join(CONFIG, "a-hand"), "H": os.path.join(CONFIG, "a-helper")}
D_VARIANTS = {"per-role-retract": variants.PerRoleRetractSM, "dup-branch": variants.DupBranchSM,
              "non-transitive": variants.NonTransitiveSM, "no-validation": variants.NoValidationSM}


def _relative(meta):
    return {k: os.path.relpath(v, CONFIG) if isinstance(v, str) and v.startswith(CONFIG) else v
            for k, v in meta.items()}


class Arm:
    def __init__(self, name, scenario, fault=None):
        self.name, self.fault = name, fault
        self.consumers = scenario["consumers"]
        sc = {"id": scenario["id"], "d": self._d(scenario["d"]), "a": dict(scenario["a"]),
              "observe": self.consumers, "steps": []}
        variant = {}
        if fault == "stale-config":
            variant["skip_changes"] = True
        if fault == "no-validation" and name != "D":
            variant["guard"] = False
        if fault in D_VARIANTS and name == "D":
            variant["sm_cls"] = D_VARIANTS[fault]
        if fault == "boundary":
            sc["a"]["initial"] = "nc-" + sc["a"]["initial"]
        if name == "D":
            self.run = core_run.DRun(sc, variant)
        else:
            self.run = core_run.ARun(sc, variant)
            self.run.arm_dir = ARM_DIRS[name]
        self.setup = _relative(self.run.start())
        self.marks = {a: 0 for a in self.consumers}
        if fault == "drop-retract":
            for a in self.consumers:
                app = self.run.apps[a]
                app.on_retract = lambda c, i, cause, app=app: app.calls.append(["dropped-retract", c, i, None])

    def _d(self, spec):
        model = spec["model"]
        if self.fault == "boundary" and model == "congestion-r0":
            model = "nc-congestion-r0"
        return {"model": os.path.join(CONFIG, "d", model), "binding": os.path.join(CONFIG, "d", spec["binding"])}

    def report(self, env):
        _, rejected = self.run.report(env)
        return rejected

    def change(self, step, now):
        a = "nc-" + step["a"] if self.fault == "boundary" and step["a"] == "TR5-r0" else step["a"]
        ch = {"id": step["id"], "a": a, "d": self._d(step["d"])}
        _, meta = self.run.change(ch, now)
        return _relative(meta)

    def validate_revision(self, step):
        """Runs the arm's pre-deployment check. Returns the refusal code, or None if accepted."""
        if self.name == "D":
            try:
                api.d_generate(self._d(step["d"]))
            except GenerationError as e:
                return e.findings[0].code
            except OrgError as e:
                return e.code
            return None
        if self.name == "A":
            found = check_plans(os.path.join(ARM_DIRS["A"], step["a"]), api.signature(), api.catalogue()[1])
            return found[0][2] if found else None
        with open(os.path.join(ARM_DIRS["H"], "source", step["helper"])) as f:
            config = yaml.safe_load(f)
        try:
            for entries in config.values():
                expand_role(entries, api.signature(), api.catalogue()[1])
        except ValueError:
            return "HELPER_REFUSED"
        return None

    def take_calls(self):
        out = []
        for a in self.consumers:
            calls = self.run.apps[a].calls
            out += [(a, c) for c in calls[self.marks[a]:]]
            self.marks[a] = len(calls)
        return out

    def view(self, agent):
        return self.run.apps[agent].view()

    def views(self):
        return {a: self.view(a) for a in self.consumers}

    def store(self):
        return self.run.store()

    def outside(self):
        return self.run.sm.stats["outside_report_cfg"] if self.name == "D" else None


def envelope(run_id, producer, context, instance, n, ts_ms, value):
    return {"schema": "rcs-env/1", "event_id": f"{run_id}:{context}:{instance}:{n}", "producer": producer,
            "pv": {"n": n, "ts": ts_ms}, "context": context, "instance": instance,
            "op": "upsert" if value is not None else "delete", "value": value}
