"""Build the helper-baseline A inputs (inputs/models/a-helper) from its A-owned config, assignment
and spec files: plans/<rev>/<Role>.yml (per-ID expansion), initial-*.yml and changes/<id>.yml
(role-based targets). Uses the shared ontology loaders only; no D parser/checker/generator.

  python tools/build_a_helper.py
"""
import os, sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from arms.a.expand import targets, write_plans  # noqa: E402
from arms.d.ontology import load_catalog, load_types, signature_of  # noqa: E402

H = os.path.join(ROOT, "inputs", "models", "a-helper")
O = os.path.join(ROOT, "inputs", "ontology")
NS = "http://ai.uos.ac.kr/logistics-ontology#"
HEADER = "# GENERATED by tools/build_a_helper.py (arms/a/expand.py) - edit config/, assign/ or spec.yml instead\n"


def y(p):
    with open(os.path.join(H, p)) as f:
        return yaml.safe_load(f)


def main():
    sig = signature_of(load_catalog(os.path.join(O, "predicates")), NS)
    types = load_types(os.path.join(O, "logistics-classes.ttl"), os.path.join(O, "logistics-individuals.ttl"))
    spec = y("spec.yml")
    written = []
    for rev, cfg in spec["revisions"].items():
        write_plans(y(cfg), os.path.join(H, rev), sig, types, HEADER)
        written.append(rev)
    for name, d in spec["initials"].items():
        p = os.path.join(H, name + ".yml")
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(HEADER)
            yaml.safe_dump({"plans": d["plans"], "agents": y(f"assign/{d['assign']}.yml")}, f, sort_keys=False)
        written.append(name)
    for name, c in spec["changes"].items():
        (fa, fp), (ta, tp) = c["from"], c["to"]
        t = targets(y(f"assign/{fa}.yml"), y(f"assign/{ta}.yml"), os.path.join(H, fp), os.path.join(H, tp))
        p = os.path.join(H, name + ".yml")
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w") as f:
            f.write(HEADER)
            yaml.safe_dump({"plans": tp, "targets": t}, f, sort_keys=False)
        written.append(name)
    print(len(written), "files/dirs written")


if __name__ == "__main__":
    main()
